def make_jpeg(path: Path, w=1536, h=1024, extra_segments: list[bytes] = (), trailer: bytes = b"") -> Path:
    from PIL import Image
    buf = io.BytesIO()
    Image.new("RGB", (w, h), (200, 160, 90)).save(buf, "JPEG", quality=60)
    data = buf.getvalue()
    data = data[:2] + b"".join(extra_segments) + data[2:] + trailer
    path.write_bytes(data)
    return path


def segment(marker: int, payload: bytes) -> bytes:
    return bytes([0xFF, marker]) + (len(payload) + 2).to_bytes(2, "big") + payload


C2PA = segment(0xEB, b"JP\x00\x01\x00\x00\x00\x01jumbc2pa xai grok imagine Grok xAI")
COM_GROK = segment(0xFE, b"Made with Grok")
EXIF_B64 = segment(0xE1, b"Exif\x00\x00" + b"9mU8AcT1U3iRCtJYKjY6wZWBTELSP6sxS3+4ef05xaIMKwzx")


def scratch_episode(tmp: Path, name="24-rajadharma") -> Path:
    dst = tmp / name
    shutil.copytree(EP24, dst, ignore=shutil.ignore_patterns("stills", "audio"))
    return dst


class ReviewCacheTests(unittest.TestCase):
    def test_record_and_invalidate(self):
        with tempfile.TemporaryDirectory() as t:
            ep = scratch_episode(Path(t))
            tool = TOOLS / "logic_review.py"
            self.assertFalse(review_cache.cached_pass(ep, "gateB", tool))
            review_cache.record(ep, "gateB", tool, True)
            self.assertTrue(review_cache.cached_pass(ep, "gateB", tool))
            (ep / "plate-bible.json").write_text((ep / "plate-bible.json").read_text() + " ")
            self.assertFalse(review_cache.cached_pass(ep, "gateB", tool))
            review_cache.record(ep, "gateB", tool, True)
            review_cache.record(ep, "gateB", tool, False)  # FAIL clears the cached PASS
            self.assertFalse(review_cache.cached_pass(ep, "gateB", tool))

    def test_cli_skip_if_unchanged(self):
        with tempfile.TemporaryDirectory() as t:
            ep = scratch_episode(Path(t))
            for tool, arg in (("logic_review.py", ep / "plate-bible.json"), ("dialogue_review.py", ep)):
                first = run(TOOLS / tool, arg, "--skip-if-unchanged")
                self.assertEqual(first.returncode, 0, first.stdout + first.stderr)
                self.assertNotIn("cached", first.stdout)
                second = run(TOOLS / tool, arg, "--skip-if-unchanged")
                self.assertIn("PASS (cached", second.stdout)
                plain = run(TOOLS / tool, arg)  # default behaviour unchanged: always full review
                self.assertNotIn("cached", plain.stdout)
            js = ep / "script.js"
            js.write_text(js.read_text() + "\n// edit\n")
            third = run(TOOLS / "dialogue_review.py", ep, "--skip-if-unchanged")
            self.assertNotIn("cached", third.stdout)


class WatermarkTests(unittest.TestCase):
    def test_c2pa_only_is_ignored(self):
        with tempfile.TemporaryDirectory() as t:
            p = make_jpeg(Path(t) / "a.jpg", extra_segments=[C2PA, EXIF_B64])
            self.assertEqual(ics.watermark_hits(p), [])
            self.assertTrue(ics.watermark_hits(p, ignore_c2pa=False))  # old behaviour still available

    def test_real_text_markers_still_flag(self):
        with tempfile.TemporaryDirectory() as t:
            p = make_jpeg(Path(t) / "b.jpg", extra_segments=[C2PA, COM_GROK])
            self.assertTrue(ics.watermark_hits(p))
            q = make_jpeg(Path(t) / "c.jpg", extra_segments=[C2PA], trailer=b"generated by grok")
            self.assertTrue(ics.watermark_hits(q))
            x = make_jpeg(Path(t) / "d.jpg", extra_segments=[segment(0xE1, b"Exif\x00\x00Software\x00xAI\x00")])
            self.assertIn("xAI", ics.watermark_hits(x))

    def test_shipped_ep24_plates_clean(self):
        plates = sorted((EP24 / "stills").glob("plate-*.jpg"))
        if not plates:
            self.skipTest("Ep24 stills not in this checkout")
        for p in plates:
            self.assertTrue(ics.watermark_hits(p, ignore_c2pa=False), p.name)  # C2PA present
            self.assertEqual(ics.watermark_hits(p), [], p.name)

    def test_corner_sheet(self):
        from PIL import Image
        with tempfile.TemporaryDirectory() as t:
            imgs = [make_jpeg(Path(t) / f"{i}.jpg") for i in range(3)]
            out = ics.write_corner_sheet(imgs, Path(t) / "sheet.jpg")
            with Image.open(out) as im:
                self.assertEqual(im.size, (260 + 4 * 206, 3 * 206 + 6))

    def test_import_end_to_end(self):
        with tempfile.TemporaryDirectory() as t:
            ep = Path(t) / "99-test"
            inbox = ep / "stills" / "_inbox" / "consumer-imagine"
            inbox.mkdir(parents=True)
            make_jpeg(inbox / "plate-one.jpg", extra_segments=[C2PA])
            ok = run(TOOLS / "import_consumer_stills.py", ep, "--inbox", inbox)
            self.assertEqual(ok.returncode, 0, ok.stdout)
            self.assertTrue((ep / "stills" / "plate-one.jpg").exists())
            self.assertTrue((ep / "stills" / "_inbox" / "corner-sheet.jpg").exists())
            make_jpeg(inbox / "plate-two.jpg", extra_segments=[C2PA, COM_GROK])
            bad = run(TOOLS / "import_consumer_stills.py", ep, "--inbox", inbox, "--force")
            self.assertEqual(bad.returncode, 1)
            self.assertIn("plate-two", bad.stdout)
            self.assertFalse((ep / "stills" / "plate-two.jpg").exists())


class CopyLocksTests(unittest.TestCase):
    def test_copy_verify_and_conflict(self):
        with tempfile.TemporaryDirectory() as t:
            root = Path(t)
            src = root / "episodes" / "10-x" / "stills" / "_locks"
            src.mkdir(parents=True)
            (src / "bhishma.jpg").write_bytes(b"lock-bytes")
            (root / "episodes" / "25-new").mkdir(parents=True)
            reg = {"bhishma": {"source": "10-x", "file": "bhishma.jpg"}}
            pairs = copy_locks.plan("25-new", ["bhishma", "bhishma:alt.jpg"], reg, root)
            self.assertEqual(copy_locks.run(pairs), [])
            dest = root / "episodes" / "25-new" / "stills" / "_locks"
            self.assertEqual((dest / "alt.jpg").read_bytes(), b"lock-bytes")
            self.assertEqual(copy_locks.run(pairs), [])  # idempotent
            (dest / "bhishma.jpg").write_bytes(b"other")
            self.assertTrue(copy_locks.run(pairs[:1]))  # differs → error without --force
            self.assertEqual(copy_locks.run(pairs[:1], force=True), [])

    def test_registry_sources_resolve(self):
        reg = copy_locks.load_registry()
        for name, ent in reg.items():
            d = ROOT / "episodes" / ent["source"]
            if d.is_dir():
                self.assertTrue((d / "stills" / "_locks" / ent["file"]).exists(), name)


class ShipRecordTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        r = Path(self.tmp.name)
        (r / "docs").mkdir()
        (r / "episodes").mkdir()
        shutil.copytree(EP24, r / "episodes" / "24-rajadharma", ignore=shutil.ignore_patterns("stills", "audio", "RR-ship.md"))
        (r / "docs" / "SPRINT_PLAN.md").write_text(
            "| Ep | Title | Branch | Status |\n|---|---|---|---|\n"
            "| 23 | *The Reluctant King* | b | **SHIPPED** 2026-10-29 |\n"
            "| 24 | planned | — | **Next** |\n\n## Weekly tally\n\n"
            "- ISO week 2026-10-26 → 2026-11-01 (Mon–Sun CT): shipped Ep 23 (*The Reluctant King*, 10-29) — **1** (x).\n")
        (r / "NEXT.md").write_text("# NEXT\n<!-- ship:now:start -->\nold\n<!-- ship:now:end -->\n")
        (r / "docs" / "HISTORY.md").write_text("# H\n<!-- history:top -->\n- older\n")
        self.root = r

    def tearDown(self):
        self.tmp.cleanup()

    def ship(self, *extra):
        return run(TOOLS / "ship_record.py", "episodes/24-rajadharma", "--root", self.root,
                   "--date", "2026-11-02", "--next", "Ep 25 (test)", *extra)

    def test_writes_and_is_idempotent(self):
        res = self.ship()
        self.assertEqual(res.returncode, 0, res.stdout + res.stderr)
        rr = (self.root / "episodes/24-rajadharma/logic-reviews/RR-ship.md").read_text()
        self.assertIn("Ship record — Ep 24 *Rajadharma*", rr)
        self.assertIn("| D install |", rr)
        self.assertIn("`orion`", rr)
        sp = (self.root / "docs/SPRINT_PLAN.md").read_text()
        self.assertIn("| 24 | *Rajadharma*", sp)
        self.assertIn("**SHIPPED** 2026-11-02", sp)
        self.assertIn("| 25 | Ep 25 (test) (planned)", sp)
        self.assertIn("ISO week 2026-11-02 → 2026-11-08 (Mon–Sun CT): shipped Ep 24 (*Rajadharma*, 11-02) — **1**", sp)
        self.assertIn("ISO week 2026-10-26", sp)  # earlier weeks untouched
        nx = (self.root / "NEXT.md").read_text()
        self.assertIn("Last ship: **Ep 24 *Rajadharma***", nx)
        self.assertNotIn("old", nx)
        self.assertIn("2026-11-09", nx)
        hist = (self.root / "docs/HISTORY.md").read_text()
        self.assertEqual(hist.count("Ep 24 *Rajadharma*"), 1)
        snapshot = {p: p.read_text() for p in self.root.rglob("*.md")}
        again = self.ship()
        self.assertEqual(again.returncode, 0)
        self.assertEqual(snapshot, {p: p.read_text() for p in self.root.rglob("*.md")})

    def test_refuses_when_gate_not_pass(self):
        rep = self.root / "episodes/24-rajadharma/logic-reviews/RR-gateC-visual.md"
        rep.write_text(rep.read_text().replace("Status: **PASS**", "Status: **FAIL**", 1))
        res = self.ship()
        self.assertEqual(res.returncode, 1)
        self.assertFalse((self.root / "episodes/24-rajadharma/logic-reviews/RR-ship.md").exists())

    def test_dry_run_writes_nothing(self):
        before = {p: p.read_text() for p in self.root.rglob("*.md")}
        self.assertEqual(self.ship("--dry-run").returncode, 0)
        self.assertEqual(before, {p: p.read_text() for p in self.root.rglob("*.md")})


